def get_localized_disease_profile(disease_id: str, lang: str, base_info: Dict[str, Any]) -> Dict[str, Any]:
    """Merge base disease info with localized regional translations."""
    lang = lang.lower()
    if lang not in LANGUAGES:
        lang = "en"
    
    localized_pack = LOCALIZED_DISEASES.get(disease_id, {}).get(lang)
    
    if localized_pack:
        return {
            "disease_name_localized": localized_pack.get("disease_name", base_info.get("disease_name")),
            "summary_localized": localized_pack.get("summary", ""),
            "voice_summary": localized_pack.get("voice_summary", ""),
            "organic_remedy_localized": [localized_pack.get("organic", "")] if localized_pack.get("organic") else base_info.get("organic_remedy", []),
            "chemical_remedy_localized": [localized_pack.get("chemical", "")] if localized_pack.get("chemical") else base_info.get("chemical_remedy", []),
            "preventive_practices_localized": [localized_pack.get("prevention", "")] if localized_pack.get("prevention") else base_info.get("preventive_practices", []),
            "lang": lang,
            "voice_code": LANGUAGES[lang]["voice_code"]
        }
    
    # Intelligent regional template generation for any crop/disease
    disease_name = base_info.get("disease_name", "Unknown Condition")
    raw_crop = base_info.get("crop", "Plant")
    pathogen = base_info.get("pathogen", "Pathogen")
    severity = base_info.get("severity_level", "Moderate")
    crop_loc = CROP_TRANSLATIONS.get(raw_crop, {}).get(lang, raw_crop)

    top_org = base_info.get("organic_remedy", ["Neem oil spray"])[0] if base_info.get("organic_remedy") else ""
